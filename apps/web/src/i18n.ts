export function systemLanguage(language: string): AppLanguage {
  return language.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en-US'
}

export function initialLanguage(): AppLanguage {
  const persisted = window.localStorage.getItem('gts-language')
  if (persisted === 'zh-CN' || persisted === 'en-US') return persisted
  return 'zh-CN'
}

export function translate(
  language: AppLanguage,
  source: string,
): string {
  return language === 'en-US' ? english[source] ?? source : source
}

export function resolveLanguage(
  preference: AppLanguagePreference,
  detected: AppLanguage,
): AppLanguage {
  return preference === 'system' ? detected : preference
}

export function translatePracticeMessage(
  language: AppLanguage,
  message?: string,
): string | undefined {
  if (!message || language === 'zh-CN') return message
  return message
    .replace(/^仅适用于 /u, 'Only available in ')
    .replace(/^至少 /u, 'At least ')
    .replace(/^最高 /u, 'Up to ')
    .replace(/^歌曲局部低至 /u, 'Song sections go as low as ')
    .replace(/^歌曲局部高至 /u, 'Song sections go as high as ')
}
